public class Diamondpyramid{
public static void main(String[]args){

for(int q=1;q<=4;q++){
for(int c=3;c>=q;c--){
System.out.print(" ");
}

for(int m=1;m<=q;m++){


System.out.print("# ");
}


System.out.println();


}


for(int i=1;i<=4;i++){

for(int s=1;s<=i;s++){

System.out.print(" ");
}

for(int j=4;j>=i;j--){


System.out.print("# ");
}


System.out.println();


}


}

}